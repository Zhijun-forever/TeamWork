def build_detail_texts(item: dict) -> tuple[str, str, str]:
    """生成结构清晰、满足 RAG 300-500 字切块需求的详情三段正文。"""
    content = (
        f"{item['title']}属于国家级/省级非物质文化遗产中的{item['category']}门类，"
        f"主要流传于贵州省{item['region']}一带。{item['summary']}\n"
        f"【艺术与工艺特征】{item['feature']}"
    )
    history = (
        f"【历史渊源与传承脉络】{item['history']}"
        f"在当地社区长期的活态实践中，该项目与节庆礼俗、生态观念和群众日常生活深度融合。"
    )
    protection = (
        f"【保护单位与保护措施】该项目保护单位为{item['protection_unit']}。"
        f"目前已建立代表性传承人建档记录、数字化影像采集、非遗进校园及活态传习工坊等系统保护机制。"
    )
    return content, history, protection


def seed_all() -> dict[str, int]:
    """向数据库幂等写入全部演示数据，返回各表最终记录数统计。"""
    from app import create_app, db
    from app.models import (
        Category,
        Certification,
        Project,
        ProjectDetail,
        Region,
        Tag,
        User,
    )

    app = create_app()
    with app.app_context():
        db.create_all()

        # 1. 初始化 4 个演示账号
        users_map: dict[str, User] = {}
        for u in DEMO_USERS:
            user = User.query.filter_by(username=u["username"]).first()
            if not user:
                user = User(
                    username=u["username"],
                    password_hash=generate_password_hash(u["password"]),
                    role=u["role"],
                    status="active",
                )
                db.session.add(user)
                db.session.flush()
            users_map[u["username"]] = user

        # 2. 初始化十大门类
        categories_map: dict[str, Category] = {}
        for name in TEN_CATEGORIES:
            cat = Category.query.filter_by(name=name).first()
            if not cat:
                cat = Category(name=name)
                db.session.add(cat)
                db.session.flush()
            categories_map[name] = cat

        # 3. 初始化省/市/县三级地区树
        regions_map: dict[str, Region] = {}
        for name, level, parent_name in REGION_TREE:
            reg = Region.query.filter_by(name=name, level=level).first()
            if not reg:
                parent_id = regions_map[parent_name].id if parent_name else None
                reg = Region(name=name, level=level, parent_id=parent_id)
                db.session.add(reg)
                db.session.flush()
            regions_map[name] = reg

        # 4. 初始化 20 个标签
        tags_map: dict[str, Tag] = {}
        for name in TWENTY_TAGS:
            tag = Tag.query.filter_by(name=name).first()
            if not tag:
                tag = Tag(name=name)
                db.session.add(tag)
                db.session.flush()
            tags_map[name] = tag

        # 5. 初始化 50 个公开非遗项目（与 manager01/admin01 归属绑定）
        base_time = datetime(2026, 11, 1, 9, 0, 0, tzinfo=timezone.utc)
        manager_user = users_map["manager01"]
        admin_user = users_map["admin01"]

        for idx, item in enumerate(RAW_PROJECTS):
            if Project.query.filter_by(title=item["title"]).first():
                continue

            owner = manager_user if idx % 2 == 0 else admin_user
            created_at = base_time + timedelta(hours=idx * 6)
            updated_at = created_at + timedelta(hours=2)

            project = Project(
                title=item["title"],
                region_id=regions_map[item["region"]].id,
                category_id=categories_map[item["category"]].id,
                owner_id=owner.id,
                status="published",
                visibility="public",
                views=item["views"],
            )
            if hasattr(Project, "summary"):
                project.summary = item["summary"]
            if hasattr(Project, "created_at"):
                project.created_at = created_at
            if hasattr(Project, "updated_at"):
                project.updated_at = updated_at

            project.tags = [tags_map[t] for t in item["tags"] if t in tags_map]
            db.session.add(project)
            db.session.flush()

            content, history, protection = build_detail_texts(item)
            db.session.add(
                ProjectDetail(
                    project_id=project.id,
                    content=content,
                    history=history,
                    protection=protection,
                )
            )

            # 为 manager01 拥有的已发布项目补齐 approved 认证记录（符合 UC-02 / BR-02）
            if owner.id == manager_user.id:
                db.session.add(
                    Certification(
                        user_id=manager_user.id,
                        project_id=project.id,
                        status="approved",
                    )
                )

        db.session.commit()

        summary = {
            "users": User.query.count(),
            "categories": Category.query.count(),
            "regions": Region.query.count(),
            "tags": Tag.query.count(),
            "projects": Project.query.count(),
        }
        return summary


if __name__ == "__main__":
    stats = seed_all()
    print("非遗数字化管理平台种子数据初始化完成：", stats)
